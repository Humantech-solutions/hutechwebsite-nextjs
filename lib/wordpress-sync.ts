const RECONCILE_THROTTLE_MS = 2 * 60 * 1000; // 2 minutes

/**
 * Non-blocking background reconciliation between iPublish and WordPress.
 * Automatically drafted unpublished posts and publishes newly published posts.
 */
export async function autoSyncMissingIPublishPosts(posts?: IPublishPageData[]): Promise<void> {
  const authSetup = getWpAuthHeaders();
  if (!authSetup) return;

  const now = Date.now();
  if (now - lastReconcileTime < RECONCILE_THROTTLE_MS) {
    return; // Throttled
  }
  lastReconcileTime = now;

  try {
    const summary = await reconcileAllIPublishPostsWithWordPress();
    console.info(`[Auto-Reconcile] ${summary.message}`);
  } catch (err: any) {
    console.warn(`[Auto-Reconcile] Background sync encountered an error:`, err?.message);
  }
}

/**
 * Removes or unpublishes a blog post from WordPress.
 *
 * User Constraints:
 * - unpublish -> draft in WordPress
 * - delete / remove -> DO NOT DELETE, KEEP IT PUBLISHED in WordPress!
 */
export async function removeWordPressPostBySlug(
  slug: string,
  mode: "trash" | "draft" | "force" = "draft",
  auth?: WpAuthConfig
): Promise<{ success: boolean; action: string; wpPostId?: number; message?: string; error?: string }> {
  const baseUrl = (auth?.baseUrl || DEFAULT_WP_BASE_URL).replace(/\/$/, "");
  const authSetup = getWpAuthHeaders(auth);

  if (!authSetup) {
    return { success: false, action: "failed", error: "Missing WordPress Application Password" };
  }

  try {
    const existing = await getExistingWpPostBySlug(slug, baseUrl, authSetup.headers);
    if (!existing || !existing.id) {
      return { success: true, action: "not_found", message: "Post does not exist in WordPress" };
    }

    if (mode === "draft") {
      // Unpublish -> Draft in WordPress
      const res = await fetch(`${baseUrl}/wp-json/wp/v2/posts/${existing.id}`, {
        method: "POST",
        headers: authSetup.headers,
        body: JSON.stringify({ status: "draft" }),
      });
      return {
        success: res.ok,
        action: "drafted",
        wpPostId: existing.id,
        message: "Post status updated to draft in WordPress.",
      };
    } else {
      // Delete or Remove -> DO NOT DELETE, KEEP PUBLISHED!
      // User constraint: "if deleted dont delete just keep it published."
      console.info(
        `[WP-Sync] Delete requested for '${slug}' (WP ID: ${existing.id}); preserving as published per user configuration.`
      );
      if (existing.status !== "publish") {
        await fetch(`${baseUrl}/wp-json/wp/v2/posts/${existing.id}`, {
          method: "POST",
          headers: authSetup.headers,
          body: JSON.stringify({ status: "publish" }),
        });
      }
      return {
        success: true,
        action: "kept_published",
        wpPostId: existing.id,
        message: "Post was removed from iPublish; preserved as published in WordPress per configuration.",
      };
    }
  } catch (error: any) {
    return { success: false, action: "failed", error: error?.message || String(error) };
  }
}
