/**
 * Synchronizes a single iPublish blog post directly into WordPress.
 *
 * Lifecycle mapping:
 * - post.status === "published" -> WordPress status "publish"
 * - post.status === "unpublished" or "draft" -> WordPress status "draft"
 * - post was deleted/removed from iPublish -> NEVER delete, keep it published!
 */
export async function syncIPublishPostToWordPress(
  post: IPublishPageData,
  auth?: WpAuthConfig
): Promise<SyncResultItem> {
  const slug = post.slug || post.id || "";
  const title = post.title || "Untitled Post";

  const baseUrl = (auth?.baseUrl || DEFAULT_WP_BASE_URL).replace(/\/$/, "");
  const authSetup = getWpAuthHeaders(auth);

  if (!authSetup) {
    return {
      slug,
      title,
      action: "failed",
      error:
        "WordPress Application Password not configured. Please set WORDPRESS_APPLICATION_PASSWORD in .env.local",
    };
  }

  try {
    // 1. Check if post already exists in WordPress
    const existing = await getExistingWpPostBySlug(slug, baseUrl, authSetup.headers);

    // 2. Determine target WordPress status
    // Rule:
    // Published in iPublish -> 'publish' in WordPress
    // Unpublished or Draft in iPublish -> 'draft' in WordPress
    const ipublishStatus = (post.status || "published").toLowerCase();
    const wpStatus: "publish" | "draft" =
      ipublishStatus === "unpublished" || ipublishStatus === "draft" ? "draft" : "publish";

    // 3. Build rich HTML content with embedded CSS, banner, images, and FAQs
    const contentHtml = buildWordPressPostContent(post);

    // 4. Resolve WordPress category IDs
    const categoryIds = resolveCategoryIds(post.subcategory);

    // 5. Build ACF Fields payload for FAQs and Author
    const acfFields: Record<string, any> = {
      author_name: post.author_name || "Hutech Solutions",
    };

    if (post.faqs && post.faqs.length > 0) {
      acfFields.faq_title = "Frequently Asked Questions";
      acfFields.faq_subtitle =
        "Common questions about this topic, answered by our experts.";
      post.faqs.slice(0, 5).forEach((faq, idx) => {
        acfFields[`faq_${idx + 1}_question`] = faq.question;
        acfFields[`faq_${idx + 1}_answer`] = faq.answer;
      });
    }

    // 6. Build SEO metadata fields for Yoast SEO, Rank Math, and custom tracking
    const seoTitle = post.seo_title || post.seo_metadata?.seo_title || title;
    const metaDesc =
      post.meta_description ||
      post.seo_metadata?.meta_description ||
      post.excerpt ||
      "";
    const focusKw = post.focus_keyword || post.seo_metadata?.focus_keyword || "";
    const canonical = post.canonical_url || post.seo_metadata?.canonical_url || "";
    const ogTitle = post.og_title || post.seo_metadata?.og_title || seoTitle;
    const ogDesc = post.og_description || post.seo_metadata?.og_description || metaDesc;

    const wpMeta: Record<string, any> = {
      _yoast_wpseo_title: seoTitle,
      _yoast_wpseo_metadesc: metaDesc,
      _yoast_wpseo_focuskw: focusKw,
      _yoast_wpseo_canonical: canonical,
      _yoast_wpseo_opengraph_title: ogTitle,
      _yoast_wpseo_opengraph_desc: ogDesc,
      rank_math_title: seoTitle,
      rank_math_description: metaDesc,
      rank_math_focus_keyword: focusKw,
      rank_math_canonical_url: canonical,
      ipublish_id: post.id || "",
      ipublish_status: post.status || "published",
      ipublish_gradient_from: post.banner_gradient_from || "",
      ipublish_gradient_to: post.banner_gradient_to || "",
      ipublish_title_color: post.title_color || "",
      ipublish_focus_keyword: focusKw,
      ipublish_synced_at: new Date().toISOString(),
    };

    // 7. Build complete post payload
    const postPayload: Record<string, any> = {
      title,
      slug,
      content: contentHtml,
      excerpt: metaDesc || post.excerpt || "",
      status: wpStatus,
      categories: categoryIds,
      fields: acfFields,
      acf: acfFields,
      meta: wpMeta,
    };

    // Preserve publication timestamp if available
    const rawDate = post.published_at || post.created_at;
    if (rawDate) {
      try {
        postPayload.date = new Date(rawDate).toISOString();
      } catch {
        // Ignore date parsing error
      }
    }

    let targetUrl: string;
    let method: string;

    if (existing && existing.id) {
      targetUrl = `${baseUrl}/wp-json/wp/v2/posts/${existing.id}`;
      method = "POST";
    } else {
      targetUrl = `${baseUrl}/wp-json/wp/v2/posts`;
      method = "POST";
    }

    const res = await fetch(targetUrl, {
      method,
      headers: authSetup.headers,
      body: JSON.stringify(postPayload),
      cache: "no-store",
    });

    if (!res.ok) {
      const errBody = await res.text();
      let errMsg = `WordPress API returned HTTP ${res.status}`;
      try {
        const parsed = JSON.parse(errBody);
        errMsg = parsed.message || parsed.code || errMsg;
      } catch {
        // Keep raw errMsg
      }
      return {
        slug,
        title,
        action: "failed",
        error: errMsg,
      };
    }

    const savedData = await res.json();
    let actionType: "created" | "updated" | "drafted" = existing ? "updated" : "created";
    if (wpStatus === "draft") {
      actionType = "drafted";
    }

    return {
      slug,
      title,
      action: actionType,
      wpPostId: savedData.id,
      status: savedData.status || wpStatus,
    };
  } catch (error: any) {
    return {
      slug,
      title,
      action: "failed",
      error: error?.message || String(error),
    };
  }
}

/**
 * Reconciles ALL iPublish posts with WordPress with full lifecycle handling:
 * - Published in iPublish -> 'publish' in WordPress
 * - Unpublished or Draft in iPublish -> 'draft' in WordPress
 * - Deleted or removed from iPublish -> NEVER delete, keep it published in WordPress!
 */
export async function reconcileAllIPublishPostsWithWordPress(
  auth?: WpAuthConfig
): Promise<SyncSummary> {
  const authSetup = getWpAuthHeaders(auth);
  const isConfigured = Boolean(authSetup);
  const baseUrl = (auth?.baseUrl || DEFAULT_WP_BASE_URL).replace(/\/$/, "");

  // 1. Fetch ALL content from iPublish with real status (published, unpublished, draft)
  const allIPublishPosts = await getAllIPublishContentWithStatus();

  if (!isConfigured) {
    return {
      total: allIPublishPosts.length,
      created: 0,
      updated: 0,
      drafted: 0,
      kept_published: 0,
      skipped: 0,
      failed: allIPublishPosts.length,
      configured: false,
      message:
        "WordPress Application Password is not configured in .env.local. Please set WORDPRESS_APPLICATION_PASSWORD (and optionally WORDPRESS_APPLICATION_USERNAME).",
      details: allIPublishPosts.map((b) => ({
        slug: b.slug || b.id || "",
        title: b.title,
        action: "failed",
        error: "Missing WORDPRESS_APPLICATION_PASSWORD",
      })),
    };
  }

  const results: SyncResultItem[] = [];
  const processedSlugs = new Set<string>();

  // 2. Sync / update each iPublish post according to its status
  for (const post of allIPublishPosts) {
    const slug = post.slug || post.id || "";
    if (slug) processedSlugs.add(slug);

    const result = await syncIPublishPostToWordPress(post, auth);
    results.push(result);
  }

  // 3. Check for any existing posts in WordPress that were deleted from iPublish
  // RULE: "if deleted dont delete just keep it published."
  if (authSetup) {
    const existingWpPosts = await getAllWordPressPosts(baseUrl, authSetup.headers);
    for (const wpPost of existingWpPosts) {
      const wpSlug = wpPost.slug;
      if (!wpSlug || processedSlugs.has(wpSlug)) {
        continue;
      }

      // Check if this post was an iPublish post (e.g. ID range or author)
      const isIPublishPost =
        wpPost.meta?.ipublish_id ||
        (wpPost.id >= 3530 && wpPost.id <= 3599);

      if (isIPublishPost) {
        // This post was deleted/removed from iPublish.
        // User rule: "if deleted dont delete just keep it published."
        if (wpPost.status !== "publish") {
          // If it was draft, ensure it is set to publish!
          try {
            await fetch(`${baseUrl}/wp-json/wp/v2/posts/${wpPost.id}`, {
              method: "POST",
              headers: authSetup.headers,
              body: JSON.stringify({ status: "publish" }),
            });
            results.push({
              slug: wpSlug,
              title: wpPost.title?.rendered || wpSlug,
              action: "kept_published",
              wpPostId: wpPost.id,
              status: "publish",
            });
          } catch {
            // Ignore error
          }
        } else {
          results.push({
            slug: wpSlug,
            title: wpPost.title?.rendered || wpSlug,
            action: "kept_published",
            wpPostId: wpPost.id,
            status: "publish",
          });
        }
      }
    }
  }

  const created = results.filter((r) => r.action === "created").length;
  const updated = results.filter((r) => r.action === "updated").length;
  const drafted = results.filter((r) => r.action === "drafted").length;
  const kept_published = results.filter((r) => r.action === "kept_published").length;
  const skipped = results.filter((r) => r.action === "skipped").length;
  const failed = results.filter((r) => r.action === "failed").length;

  return {
    total: allIPublishPosts.length,
    created,
    updated,
    drafted,
    kept_published,
    skipped,
    failed,
    configured: true,
    message: `Reconciliation completed: ${created} created, ${updated} updated, ${drafted} drafted, ${kept_published} kept published, ${failed} failed.`,
    details: results,
  };
}

/**
 * Backward compatible alias for syncAllIPublishPostsToWordPress.
 */
export async function syncAllIPublishPostsToWordPress(auth?: WpAuthConfig): Promise<SyncSummary> {
  return reconcileAllIPublishPostsWithWordPress(auth);
}

/**
 * Checks current synchronization status between iPublish and WordPress.
 */
export async function getWordPressSyncStatus(auth?: WpAuthConfig): Promise<{
  configured: boolean;
  totalIPublishPosts: number;
  ipublishPosts: {
    slug: string;
    title: string;
    status: string;
    subcategory?: string;
    existsInWp: boolean;
    wpStatus?: string;
    wpPostId?: number;
  }[];
}> {
  const baseUrl = (auth?.baseUrl || DEFAULT_WP_BASE_URL).replace(/\/$/, "");
  const authSetup = getWpAuthHeaders(auth);
  const allIPublishPosts = await getAllIPublishContentWithStatus();

  const ipublishPosts = await Promise.all(
    allIPublishPosts.map(async (post) => {
      const slug = post.slug || post.id || "";
      const existing = await getExistingWpPostBySlug(slug, baseUrl, authSetup?.headers);
      return {
        slug,
        title: post.title,
        status: post.status || "published",
        subcategory: post.subcategory,
        existsInWp: Boolean(existing),
        wpStatus: existing?.status,
        wpPostId: existing?.id,
      };
    })
  );

  return {
    configured: Boolean(authSetup),
    totalIPublishPosts: allIPublishPosts.length,
    ipublishPosts,
  };
}

