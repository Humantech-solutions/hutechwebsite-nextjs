/**
 * Normalizes credentials and returns Authorization headers for WordPress REST API.
 * WordPress 5.6+ natively supports Application Passwords (Basic Auth).
 */
export function getWpAuthHeaders(auth?: WpAuthConfig): { headers: Record<string, string> } | null {
  const username =
    auth?.username ||
    process.env.WORDPRESS_APPLICATION_USERNAME ||
    process.env.WORDPRESS_USERNAME ||
    process.env.WP_USERNAME ||
    "admin";

  const rawPassword =
    auth?.applicationPassword ||
    process.env.WORDPRESS_APPLICATION_PASSWORD ||
    process.env.WP_APP_PASSWORD ||
    process.env.WORDPRESS_APP_PASSWORD;

  if (!rawPassword || rawPassword.trim() === "") {
    return null;
  }

  // Application passwords generated by WordPress can contain spaces for readability (e.g., 'xxxx xxxx xxxx xxxx')
  // Spaces must be stripped when base64 encoding for Basic Auth
  const cleanPassword = rawPassword.replace(/\s+/g, "");
  const basicAuth = Buffer.from(`${username.trim()}:${cleanPassword}`).toString("base64");

  return {
    headers: {
      Authorization: `Basic ${basicAuth}`,
      "Content-Type": "application/json",
      Accept: "application/json",
    },
  };
}

