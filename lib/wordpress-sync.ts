/**
 * Resolves WordPress category IDs based on the iPublish post's subcategory.
 */
function resolveCategoryIds(subcategory?: string): number[] {
  if (!subcategory || !subcategory.trim()) {
    return [10]; // Default to "Technology"
  }

  const parts = subcategory
    .toLowerCase()
    .split(/[,/]+/)
    .map((s) => s.trim())
    .filter(Boolean);

  const matchedIds = new Set<number>();

  for (const part of parts) {
    if (CATEGORY_MAP[part]) {
      matchedIds.add(CATEGORY_MAP[part].id);
    } else {
      // Fuzzy match
      const key = Object.keys(CATEGORY_MAP).find((k) => part.includes(k) || k.includes(part));
      if (key) {
        matchedIds.add(CATEGORY_MAP[key].id);
      }
    }
  }

  if (matchedIds.size === 0) {
    matchedIds.add(10); // Fallback to "Technology"
  }

  return Array.from(matchedIds);
}

/**
 * Fetches existing WordPress post by slug (checks any post status: publish, draft, future, private).
 */
export async function getExistingWpPostBySlug(
  slug: string,
  baseUrl: string,
  authHeaders?: Record<string, string>
): Promise<any | null> {
  try {
    const url = `${baseUrl.replace(/\/$/, "")}/wp-json/wp/v2/posts?slug=${encodeURIComponent(
      slug
    )}&status=any`;
    const res = await fetch(url, {
      headers: authHeaders || {},
      cache: "no-store",
    });

    if (!res.ok) {
      return null;
    }

    const data = await res.json();
    return Array.isArray(data) && data.length > 0 ? data[0] : null;
  } catch (error) {
    console.error(`[WP-Sync] Error checking existing post for '${slug}':`, error);
    return null;
  }
}

/**
 * Fetches all posts authored by or associated with iPublish from WordPress.
 */
export async function getAllWordPressPosts(
  baseUrl: string,
  authHeaders?: Record<string, string>
): Promise<any[]> {
  try {
    const url = `${baseUrl.replace(/\/$/, "")}/wp-json/wp/v2/posts?status=any&per_page=100`;
    const res = await fetch(url, {
      headers: authHeaders || {},
      cache: "no-store",
    });

    if (!res.ok) {
      return [];
    }

    const data = await res.json();
    return Array.isArray(data) ? data : [];
  } catch (error) {
    console.error("[WP-Sync] Error fetching all WordPress posts:", error);
    return [];
  }
}

