/**
 * Centralized Logo Resolver - Guarantees each technology receives its distinct, non-repeated vector icon
 */
export function getTechVectorLogo(slug: string, className = "w-6 h-6") {
  const s = (slug || "").toLowerCase();

  if (s.includes("java")) {
    return <JavaLogo className={className} />;
  }
  if (s.includes("dotnet") || s.includes(".net") || s === "net") {
    return <DotNetLogo className={className} />;
  }
  if (s.includes("php")) {
    return <PhpLogo className={className} />;
  }
  if (s.includes("ruby") || s.includes("rail")) {
    return <RailsLogo className={className} />;
  }
  if (s.includes("cobol")) {
    return <CobolLogo className={className} />;
  }
  if (s.includes("python")) {
    return <PythonLogo className={className} />;
  }

  return <JavaLogo className={className} />;
}
